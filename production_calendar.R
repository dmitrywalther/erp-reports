# Продолжение федерального календаря. Данные локальные: при запуске сеть не нужна.
# Праздники: ст. 112 ТК РФ; даты переноса включают автоматический перенос
# совпавшего с выходным праздника и исключения из постановлений Правительства:
# 2023: 29.08.2022 №1505 — https://government.ru/docs/46378/
# 2024: 10.08.2023 №1314 — https://publication.pravo.gov.ru/document/0001202308180053
# 2025: 04.10.2024 №1335 — https://government.ru/docs/52895/
# 2026: 24.09.2025 №1466 — https://publication.pravo.gov.ru/document/0001202509240023
# 2027: 17.09.2026 №1187 — https://publication.pravo.gov.ru/document/0001202609180037
# Не экстраполировать переносы на последующие годы: сначала добавить постановление
# и обновить проверку годовых итогов в demo/test_calendar.R.
transition_table_workDay <- local({
  dates <- seq(as.Date("2023-07-01"), as.Date("2027-12-31"), by = "day")
  public_holidays <- c(sprintf("01-%02d", 1:8), "02-23", "03-08", "05-01", "05-09", "06-12", "11-04")
  transferred_days_off <- as.Date(c(
    "2023-11-06",
    "2024-04-29", "2024-04-30", "2024-05-10", "2024-12-30", "2024-12-31",
    "2025-05-02", "2025-05-08", "2025-06-13", "2025-11-03", "2025-12-31",
    "2026-01-09", "2026-03-09", "2026-05-11", "2026-12-31",
    "2027-02-22", "2027-05-03", "2027-05-10", "2027-06-14", "2027-11-05", "2027-12-31"
  ))
  working_saturdays <- as.Date(c(
    "2024-04-27", "2024-11-02", "2024-12-28", "2025-11-01", "2027-02-20"
  ))
  working <- !as.POSIXlt(dates)$wday %in% c(0, 6) &
    !format(dates, "%m-%d") %in% public_holidays &
    !dates %in% transferred_days_off
  working[dates %in% working_saturdays] <- TRUE
  continuation <- data.frame(Дата = dates, Рабочих_дней = as.integer(working), check.names = FALSE)
  rbind(transition_table_workDay, continuation)
})

# Проверка перед KPI join не даёт незаметно потерять строки за пределами
# опубликованного календаря. Никакого приблизительного weekday-fallback нет.
production_calendar_for_dates <- function(dates) {
  if (!inherits(dates, "Date")) stop("Для календаря нужны даты класса Date", call. = FALSE)
  missing <- is.na(dates) | !dates %in% transition_table_workDay$Дата
  if (any(missing)) {
    stop(sprintf("Производственный календарь доступен с %s по %s. Обновите календарь или выберите период в этом диапазоне.",
                 min(transition_table_workDay$Дата), max(transition_table_workDay$Дата)), call. = FALSE)
  }
  transition_table_workDay
}
